-- Criação da tabela de conta de pagamento
CREATE TABLE conta_pagamento (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    acct_info_id BIGINT,
    name VARCHAR(255),
    email VARCHAR(255),
    addr_match VARCHAR(255),
    bill_addr_country VARCHAR(255),
    bill_addr_city VARCHAR(255),
    bill_addr_line1 VARCHAR(255),
    bill_addr_line2 VARCHAR(255),
    bill_addr_line3 VARCHAR(255),
    bill_addr_post_code VARCHAR(255),
    bill_addr_state VARCHAR(255),
    ship_addr_country VARCHAR(255),
    ship_addr_city VARCHAR(255),
    ship_addr_line1 VARCHAR(255),
    ship_addr_post_code VARCHAR(255),
    ship_addr_state VARCHAR(255),
    work_phone_id BIGINT,
    mobile_phone_id BIGINT,
    CONSTRAINT fk_acct_info FOREIGN KEY (acct_info_id) REFERENCES info_conta_pagamento(id),
    CONSTRAINT fk_work_phone FOREIGN KEY (work_phone_id) REFERENCES contato_conta_pagamento(id),
    CONSTRAINT fk_mobile_phone FOREIGN KEY (mobile_phone_id) REFERENCES contato_conta_pagamento(id)
);
