-- Criação da tabela de configuração de pagamento
CREATE TABLE configuracao_pagamento (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    pos_id VARCHAR(255) NOT NULL UNIQUE,
    merchant_id VARCHAR(255) NOT NULL,
    api_key VARCHAR(255) NOT NULL,
    api_secret VARCHAR(255) NOT NULL,
    pos_aut_code VARCHAR(255) NOT NULL,
    return_aut_code VARCHAR(255) NOT NULL,
    return_url VARCHAR(255) NOT NULL DEFAULT 'https://localhost:8443/admin/pagamentos',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    nome_loja VARCHAR(255) NOT NULL,
    url_loja VARCHAR(255) NOT NULL,
    telefone VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    ambiente VARCHAR(50) NOT NULL,
    webhook_url VARCHAR(255),
    webhook_secret VARCHAR(255) NOT NULL,
    webhook_ativo BOOLEAN DEFAULT FALSE,
    return_ativo BOOLEAN DEFAULT TRUE,
    ativo BOOLEAN DEFAULT TRUE,
    observacoes TEXT,
    usuario_id BIGINT,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME,
    terminal_id VARCHAR(255) NOT NULL DEFAULT '',
    service_url VARCHAR(255) NOT NULL DEFAULT '',
    CONSTRAINT fk_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
    CONSTRAINT uk_pos_id UNIQUE (pos_id)
);
